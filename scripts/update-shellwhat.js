import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const outputFile = path.join(rootDir, 'src', 'runtime', 'shellwhatSources.ts');

const GITHUB_API_URL = 'https://api.github.com/repos/datacamp/shellwhat/contents/shellwhat';
const RAW_BASE_URL = 'https://raw.githubusercontent.com/datacamp/shellwhat/master/shellwhat';

async function fetchJson(url) {
  const response = await fetch(url, {
    headers: {
      'User-Agent': 'datacamp-light-update-shellwhat-script',
    },
  });
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status} ${response.statusText}`);
  }
  return response.json();
}

async function fetchText(url) {
  const response = await fetch(url, {
    headers: {
      'User-Agent': 'datacamp-light-update-shellwhat-script',
    },
  });
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status} ${response.statusText}`);
  }
  return response.text();
}

async function updateShellwhat() {
  console.log('Fetching shellwhat Python file listing from GitHub...');
  const rootItems = await fetchJson(GITHUB_API_URL);
  const sources = {};

  for (const item of rootItems) {
    if (item.type === 'file' && item.name.endsWith('.py')) {
      const rawUrl = `${RAW_BASE_URL}/${item.name}`;
      console.log(`- Downloading ${item.name}...`);
      sources[item.name] = await fetchText(rawUrl);
    } else if (item.type === 'dir' && item.name === 'checks') {
      const checkItems = await fetchJson(item.url);
      for (const checkItem of checkItems) {
        if (checkItem.type === 'file' && checkItem.name.endsWith('.py')) {
          const rawUrl = `${RAW_BASE_URL}/checks/${checkItem.name}`;
          console.log(`- Downloading checks/${checkItem.name}...`);
          sources[`checks/${checkItem.name}`] = await fetchText(rawUrl);
        }
      }
    }
  }

  const fileContent = `// Auto-generated by scripts/update-shellwhat.js
// Do not edit directly. Run \`npm run update:shellwhat\` to re-generate from github.com/datacamp/shellwhat.

export const SHELLWHAT_PY_SOURCES: Record<string, string> = ${JSON.stringify(sources, null, 2)};
`;

  fs.writeFileSync(outputFile, fileContent, 'utf8');
  console.log(`Successfully updated shellwhat sources at ${outputFile}`);
}

updateShellwhat().catch((error) => {
  console.error('Error updating shellwhat sources:', error);
  process.exit(1);
});
