import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const outputFile = path.join(rootDir, 'src', 'runtime', 'testwhatSources.ts');

const GITHUB_API_URL = 'https://api.github.com/repos/datacamp/testwhat/contents/R';
const RAW_BASE_URL = 'https://raw.githubusercontent.com/datacamp/testwhat/master/R';

async function fetchJson(url) {
  const response = await fetch(url, {
    headers: {
      'User-Agent': 'datacamp-light-update-testwhat-script',
    },
  });
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status} ${response.statusText}`);
  }
  return response.json();
}

async function fetchText(url) {
  const response = await fetch(url, {
    headers: {
      'User-Agent': 'datacamp-light-update-testwhat-script',
    },
  });
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status} ${response.statusText}`);
  }
  return response.text();
}

async function updateTestwhat() {
  console.log('Fetching testwhat R file listing from GitHub...');
  const files = await fetchJson(GITHUB_API_URL);
  const rFiles = files.filter((f) => f.name.endsWith('.R')).sort((a, b) => a.name.localeCompare(b.name));

  console.log(`Found ${rFiles.length} R source files. Downloading contents...`);
  const sources = {};

  for (const file of rFiles) {
    const rawUrl = `${RAW_BASE_URL}/${file.name}`;
    console.log(`- Downloading ${file.name}...`);
    const content = await fetchText(rawUrl);
    sources[file.name] = content;
  }

  const fileContent = `// Auto-generated by scripts/update-testwhat.js
// Do not edit directly. Run \`npm run update:testwhat\` to re-generate.

export const TESTWHAT_R_SOURCES: Record<string, string> = ${JSON.stringify(sources, null, 2)};
`;

  fs.writeFileSync(outputFile, fileContent, 'utf8');
  console.log(`Successfully updated testwhat sources at ${outputFile}`);
}

updateTestwhat().catch((error) => {
  console.error('Error updating testwhat sources:', error);
  process.exit(1);
});
